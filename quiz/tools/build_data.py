"""Build quiz/data/questions.js from the quiz text.

Convert the Word export to Markdown first:
    pandoc Quiz.docx -t markdown-smart --wrap=none -o quiz/tools/quiz-source.md
then run:
    python3 quiz/tools/build_data.py quiz/tools/quiz-source.md quiz/data/questions.js
"""
import html, json, re, sys

MARK = "(the book's reading)"


def inline(s):
    s = s.replace("\\@", "@")
    s = re.sub(r"\\(.)", r"\1", s)
    s = curly(s)
    s = html.escape(s, quote=False)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\*(.+?)\*", r"<em>\1</em>", s)
    return s.strip()


def curly(s):
    """Typographic quotes: opening after a space, bracket, dash, or line start; closing otherwise."""
    s = re.sub(r'(^|[\s(\[\u2014\u2013])"', "\\1\u201c", s)
    s = s.replace('"', "\u201d")
    s = re.sub(r"(^|[\s(\[\u2014\u2013])'", "\\1\u2018", s)
    return s.replace("'", "\u2019")


def strip_mark(s):
    found = False
    for pat in (r"\s*\*\(the book\\?'s reading\)\*", r"\s*\(the book\\?'s reading\)"):
        if re.search(pat, s):
            found = True
            s = re.sub(pat, "", s)
    return s.strip(), found


def parse(text):
    lines = text.splitlines()
    title = intro = None
    part = chapter = None
    sections, questions, q = [], [], None
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        if line.startswith("# "):
            title = inline(line[2:])
            continue
        if line.startswith("## "):
            part = inline(line[3:])
            chapter = None
            if part.startswith("Introduction"):
                chapter = part
                sections.append({"part": "Introduction", "chapter": part})
            continue
        if line.startswith("### "):
            chapter = inline(line[4:])
            sections.append({"part": part, "chapter": chapter})
            continue
        m = re.match(r"\*\*(\d+)\.\*\*\s*(.*)", line)
        if m:
            stem, flag = strip_mark(m.group(2))
            q = {"n": int(m.group(1)), "section": len(sections) - 1,
                 "stem": inline(stem), "options": [], "reading": flag}
            questions.append(q)
            continue
        m = re.match(r"-\s+([A-D])\.\s+(.*)", line)
        if m and q:
            q["options"].append(inline(m.group(2)))
            continue
        m = re.match(r"\*\*Answer: ([A-D])\.\*\*\s*(.*)", line)
        if m and q:
            expl, flag = strip_mark(m.group(2))
            q["answer"] = "ABCD".index(m.group(1))
            q["explanation"] = inline(expl)
            q["reading"] = q["reading"] or flag
            continue
        if q and q.get("options") and "answer" not in q and not line.startswith("-"):
            q["options"][-1] += " " + inline(line)  # wrapped option
            continue
        if title and intro is None and not questions and not line.startswith(("Nov", "Oct")) and "@" not in line:
            intro = inline(line)
    for q in questions:
        assert len(q["options"]) == 4 and "answer" in q, q["n"]
    return {"title": title, "intro": intro, "sections": sections, "questions": questions}


if __name__ == "__main__":
    src, out = sys.argv[1], sys.argv[2]
    data = parse(open(src, encoding="utf-8").read())
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by quiz/tools/build_data.py from quiz/tools/quiz-source.md. Edit the source, then rebuild.\n")
        f.write("window.QUIZ = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    print(len(data["questions"]), "questions,", len(data["sections"]), "sections,",
          sum(q["reading"] for q in data["questions"]), "marked as the book's reading")
